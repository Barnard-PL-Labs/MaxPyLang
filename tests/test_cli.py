"""
`maxpylang setup-agent` writes the agent guide into AGENTS.md without touching anything else
the user wrote there, and makes CLAUDE.md import it.
"""

import subprocess
import sys

import pytest

from maxpylang import cli


@pytest.fixture
def project(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    return tmp_path


def run(*args):
    with pytest.raises(SystemExit) as exit_info:
        cli.main(list(args))
    return exit_info.value.code


def test_creates_agents_and_claude(project):
    assert run("setup-agent") == 0

    agents = (project / "AGENTS.md").read_text()
    assert agents.startswith(f"<!-- maxpylang:begin version={cli.package_version()} -->")
    assert agents.rstrip().endswith("<!-- maxpylang:end -->")
    assert "## Check before you run" in agents
    assert (project / "CLAUDE.md").read_text() == "@AGENTS.md\n"


def test_keeps_user_text_and_refreshes_only_the_block(project):
    (project / "AGENTS.md").write_text("# My project\n\nUse tabs.\n")
    (project / "CLAUDE.md").write_text("Be terse.\n")

    run("setup-agent")
    first = (project / "AGENTS.md").read_text()
    assert first.startswith("# My project\n\nUse tabs.\n\n<!-- maxpylang:begin")
    assert (project / "CLAUDE.md").read_text() == "Be terse.\n@AGENTS.md\n"

    # an outdated block is replaced in place, and nothing is added twice
    (project / "AGENTS.md").write_text(
        first.replace(f"version={cli.package_version()}", "version=0.0.1") + "\nMore notes.\n")
    run("setup-agent")
    second = (project / "AGENTS.md").read_text()
    assert second == first + "\nMore notes.\n"
    assert second.count("<!-- maxpylang:begin") == 1
    assert (project / "CLAUDE.md").read_text() == "Be terse.\n@AGENTS.md\n"


def test_no_claude(project):
    run("setup-agent", "--no-claude")
    assert (project / "AGENTS.md").exists()
    assert not (project / "CLAUDE.md").exists()


def test_setup_claude_is_an_alias(project):
    # older instructions say `setup-claude --force`
    assert run("setup-claude", "--force") == 0
    assert (project / "AGENTS.md").exists()
    assert (project / "CLAUDE.md").read_text() == "@AGENTS.md\n"


def test_notes_an_old_setup_claude_copy(project, capsys):
    (project / "CLAUDE.md").write_text("# MaxPyLang\n\n> Generated by `maxpylang setup-claude`. This file...\n")
    run("setup-agent")
    assert "older copy of the guide" in capsys.readouterr().out
    assert (project / "CLAUDE.md").read_text().endswith("@AGENTS.md\n")


def test_python_dash_m(project):
    result = subprocess.run([sys.executable, "-m", "maxpylang", "setup-agent"],
                            cwd=project, capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    assert (project / "AGENTS.md").exists()
