"""
Build one Max patch that renders many fxgen devices at once, each to its own WAV.

Every device is generated by fxgen exactly as the page generates it, with two swaps:
sfplay~ stands in for plugin~ and sfrecord~ for plugout~. So the test signal goes in from
a file, the result goes out to a file, and nothing reaches the speakers. The patch starts
audio on load, records, and quits Max when it is done.

    python max_batch.py tests.json signal.wav <seconds> <outdir>
    open -W -a Max <outdir>/batch.maxpat      # about half a minute; Max opens and closes

Do not run it while you have unsaved work open in Max: the patch ends with `; max quit`.
"""
import sys, json, os, re, copy
import pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "web" / "src" / "plugin"))
import fxgen

def device(name, settings):
    src = fxgen.script(settings)
    src = src.replace('place("plugin~"', 'place("sfplay~ 2"').replace('place("plugout~"', 'place("sfrecord~ 2"')
    src = re.sub(r'patch\.save\(.*\)\s*$', '', src.rstrip()) + "\n"
    ns = {}
    exec(compile(src, name, "exec"), ns)
    return ns["patch"].get_json()

def build(tests, wav_in, secs, outdir):
    master = None
    plays, recs, outs = [], [], []
    for k, (name, settings) in enumerate(tests):
        j = device(name, settings)
        p = j["patcher"]
        pre = "d%d-" % k
        for b in p["boxes"]:
            bx = b["box"]; bx["id"] = pre + bx["id"]
            r = bx.get("patching_rect"); r[0] += k * 1500.0
            bx.pop("presentation", None); bx.pop("presentation_rect", None)
            bx.pop("varname", None)
            sa = bx.get("saved_attribute_attributes", {}).get("valueof")
            if sa:  # parameter names must stay unique across the merged patch
                sa["parameter_longname"] = "%s %s" % (name, sa["parameter_longname"])
            if bx.get("text") == "sfplay~ 2": plays.append(bx["id"])
            if bx.get("text") == "sfrecord~ 2": recs.append(bx["id"])
        for l in p["lines"]:
            pl = l["patchline"]; pl["source"][0] = pre + pl["source"][0]; pl["destination"][0] = pre + pl["destination"][0]
        if master is None:
            master = j; master["patcher"]["openinpresentation"] = 0
        else:
            master["patcher"]["boxes"] += p["boxes"]; master["patcher"]["lines"] += p["lines"]
        outs.append(os.path.join(outdir, name + ".wav"))
    boxes, lines = master["patcher"]["boxes"], master["patcher"]["lines"]
    n = [0]
    def add(maxclass, text, x, y, nin=1, nout=1):
        n[0] += 1; i = "h-%d" % n[0]
        b = {"id": i, "maxclass": maxclass, "text": text, "numinlets": nin, "numoutlets": nout,
             "patching_rect": [float(x), float(y), 260.0, 22.0]}
        if nout: b["outlettype"] = [""] * nout
        boxes.append({"box": b}); return i
    def wire(a, ao, b, bi): lines.append({"patchline": {"source": [a, ao], "destination": [b, bi]}})
    x = -400
    lb = add("newobj", "loadbang", x, 20)
    d0 = add("newobj", "delay 2500", x, 50, 2, 1)
    dsp = add("message", ";\rdsp start", x, 80, 2, 1)
    da = add("newobj", "delay 2500", x, 120, 2, 1)
    d1 = add("newobj", "delay 800", x, 160, 2, 1)
    on = add("message", "1", x, 200, 2, 1)
    d2 = add("newobj", "delay %d" % int(secs * 1000), x, 240, 2, 1)
    off = add("message", "0", x, 280, 2, 1)
    d3 = add("newobj", "delay 1500", x, 320, 2, 1)
    quit_ = add("message", ";\rmax quit", x, 360, 2, 1)
    wire(lb, 0, d0, 0); wire(d0, 0, dsp, 0); wire(d0, 0, da, 0); wire(da, 0, d1, 0)
    wire(d1, 0, on, 0); wire(d1, 0, d2, 0); wire(d2, 0, off, 0); wire(d2, 0, d3, 0); wire(d3, 0, quit_, 0)
    for k, (pl, rc, out) in enumerate(zip(plays, recs, outs)):
        oin = add("message", "open %s" % wav_in, x, 420 + 60 * k, 2, 1)
        oout = add("message", "open %s wave" % out, x, 450 + 60 * k, 2, 1)
        wire(da, 0, oin, 0); wire(da, 0, oout, 0); wire(oin, 0, pl, 0); wire(oout, 0, rc, 0)
        wire(on, 0, pl, 0); wire(on, 0, rc, 0); wire(off, 0, rc, 0)
    path = os.path.join(outdir, "batch.maxpat")
    json.dump(master, open(path, "w"), indent=1)
    return path

if __name__ == "__main__":
    tests = json.load(open(sys.argv[1]))
    outdir = sys.argv[4]; os.makedirs(outdir, exist_ok=True)
    print(build([(t["name"], t["settings"]) for t in tests], sys.argv[2], float(sys.argv[3]), outdir), len(tests))
