"""The module-by-module test settings: every option, and each dial at its ends.
Writes tests.json in the current directory."""
import json
T=[]
def t(name, chain, gain=0): T.append({"name":name,"settings":{"name":name,"chain":chain,"output":{"gain":gain}}})
t("init", [])
for k in ("soft","tube","hard","fuzz","fold"):
    for a in (1, 3, 10): t("drive_%s_%d"%(k,a), [{"module":"drive","options":{"character":k},"values":{"amount":a,"tone":10000}}])
t("drive_tone_1000", [{"module":"drive","options":{"character":"soft"},"values":{"amount":1,"tone":1000}}])
for m in ("lowpass","highpass","bandpass","notch"):
    t("filter_%s"%m, [{"module":"filter","options":{"mode":m},"values":{"cutoff":1000,"res":30}}])
for r in (0, 50, 100): t("filter_lp_res%d"%r, [{"module":"filter","options":{"mode":"lowpass"},"values":{"cutoff":1000,"res":r}}])
for c in (100, 5000, 10000): t("filter_lp_%d"%c, [{"module":"filter","options":{"mode":"lowpass"},"values":{"cutoff":c,"res":30}}])
t("filter_hp_10000_res100", [{"module":"filter","options":{"mode":"highpass"},"values":{"cutoff":10000,"res":100}}])
t("filter_bp_300_res100", [{"module":"filter","options":{"mode":"bandpass"},"values":{"cutoff":300,"res":100}}])
for r,b in ((100,16),(35,8),(10,16),(100,4),(2,2)): t("crush_%d_%d"%(r,b), [{"module":"crush","values":{"rate":r,"bits":b}}])
t("chorus_def", [{"module":"chorus","options":{"voice":"chorus"},"values":{"rate":0.6,"depth":3,"mix":50}}])
t("chorus_max", [{"module":"chorus","options":{"voice":"chorus"},"values":{"rate":8,"depth":8,"mix":100}}])
t("flanger_def", [{"module":"chorus","options":{"voice":"flanger"},"values":{"rate":0.3,"depth":5,"mix":50}}])
t("flanger_static", [{"module":"chorus","options":{"voice":"flanger"},"values":{"rate":0.05,"depth":0,"mix":100}}])
t("chorus_static", [{"module":"chorus","options":{"voice":"chorus"},"values":{"rate":0.05,"depth":0,"mix":100}}])
t("flanger_max", [{"module":"chorus","options":{"voice":"flanger"},"values":{"rate":8,"depth":8,"mix":100}}])
t("trem_def", [{"module":"tremolo","options":{"mode":"tremolo"},"values":{"rate":5,"depth":60}}])
t("trem_full", [{"module":"tremolo","options":{"mode":"tremolo"},"values":{"rate":5,"depth":100}}])
t("trem_pan", [{"module":"tremolo","options":{"mode":"autopan"},"values":{"rate":2,"depth":100}}])
t("delay_def", [{"module":"delay","options":{"style":"stereo"},"values":{"time":320,"feedback":40,"mix":30}}])
t("delay_wet", [{"module":"delay","options":{"style":"stereo"},"values":{"time":250,"feedback":0,"mix":100}}])
t("delay_fb90", [{"module":"delay","options":{"style":"stereo"},"values":{"time":100,"feedback":90,"mix":50}}])
t("delay_ping", [{"module":"delay","options":{"style":"pingpong"},"values":{"time":200,"feedback":60,"mix":100}}])
t("delay_min", [{"module":"delay","options":{"style":"stereo"},"values":{"time":10,"feedback":50,"mix":100}}])
for s in (0, 55, 100): t("reverb_size%d"%s, [{"module":"reverb","values":{"size":s,"damp":10000,"mix":100}}])
t("reverb_def", [{"module":"reverb","values":{"size":55,"damp":6000,"mix":25}}])
t("reverb_damp500", [{"module":"reverb","values":{"size":55,"damp":500,"mix":100}}])
t("delay_def_eq", [{"module":"delay","options":{"style":"stereo"},"values":{"time":320,"feedback":40,"mix":50}}])
t("chain_all", [{"module":"filter"},{"module":"drive"},{"module":"crush"},{"module":"chorus"},{"module":"tremolo"},{"module":"delay"},{"module":"reverb"}])
t("out_p12", [], 12); t("out_m24", [], -24)
json.dump(T, open("tests.json","w"))
print(len(T))
