"""
Command-line interface for maxpylang.

    maxpylang setup-agent   --> write the agent guide into ./AGENTS.md
    python -m maxpylang setup-agent   (same, when the maxpylang script is not on PATH)

AGENTS.md is read by most coding agents (Codex, Cursor, ...). Claude Code reads CLAUDE.md,
so setup-agent also makes CLAUDE.md import AGENTS.md with one "@AGENTS.md" line.

The guide sits between two marker lines. Running setup-agent again replaces only the text
between them, so anything else the user wrote in AGENTS.md or CLAUDE.md is kept.
"""
from __future__ import annotations

import argparse
import re
import sys
from importlib.metadata import PackageNotFoundError, version
from importlib.resources import files
from pathlib import Path

GUIDE_FILE = "AGENTS.md"
CLAUDE_FILE = "CLAUDE.md"
CLAUDE_IMPORT = "@AGENTS.md"

BEGIN = "<!-- maxpylang:begin version={version} -->"
END = "<!-- maxpylang:end -->"
_BLOCK = re.compile(r"<!-- maxpylang:begin[^>]*-->.*?<!-- maxpylang:end -->\n?", re.DOTALL)

# first line of the CLAUDE.md that `setup-claude` wrote before setup-agent existed
_OLD_CLAUDE_HEADER = "> Generated by `maxpylang setup-claude`."


def package_version() -> str:
    """Installed maxpylang version, or "unknown" when running from an uninstalled tree."""
    try:
        return version("maxpylang")
    except PackageNotFoundError:
        return "unknown"


def guide_block() -> str:
    """The agent guide, wrapped in marker lines that carry the maxpylang version."""
    guide = files("maxpylang").joinpath("data", "AGENTS_TEMPLATE.md").read_text(encoding="utf-8")
    return f"{BEGIN.format(version=package_version())}\n{guide.rstrip()}\n{END}\n"


def write_guide(path: Path) -> str:
    """Create AGENTS.md, or replace or append the maxpylang block in it. Returns what was done."""
    block = guide_block()
    if not path.exists():
        path.write_text(block, encoding="utf-8")
        return "created"

    text = path.read_text(encoding="utf-8")
    if _BLOCK.search(text):
        path.write_text(_BLOCK.sub(lambda _: block, text, count=1), encoding="utf-8")
        return "updated"

    sep = "" if text.endswith("\n\n") or not text else ("\n" if text.endswith("\n") else "\n\n")
    path.write_text(text + sep + block, encoding="utf-8")
    return "appended to"


def link_claude(path: Path) -> str | None:
    """Make CLAUDE.md import AGENTS.md. Returns what was done, or None if nothing changed."""
    if not path.exists():
        path.write_text(CLAUDE_IMPORT + "\n", encoding="utf-8")
        return "created"

    text = path.read_text(encoding="utf-8")
    if any(line.strip() == CLAUDE_IMPORT for line in text.splitlines()):
        return None

    sep = "" if not text or text.endswith("\n") else "\n"
    path.write_text(text + sep + CLAUDE_IMPORT + "\n", encoding="utf-8")
    return "updated"


def setup_agent(args: argparse.Namespace) -> int:
    """Write the agent guide into AGENTS.md in the current directory, and link CLAUDE.md to it."""
    cwd = Path.cwd()
    guide_path = cwd / GUIDE_FILE
    claude_path = cwd / CLAUDE_FILE

    try:
        done = write_guide(guide_path)
        print(f"{done.capitalize()} {guide_path} (maxpylang {package_version()} agent guide)")

        if not args.no_claude:
            old_copy = claude_path.exists() and _OLD_CLAUDE_HEADER in claude_path.read_text(encoding="utf-8")
            linked = link_claude(claude_path)
            if linked:
                print(f"{linked.capitalize()} {claude_path} so Claude Code reads {GUIDE_FILE} ({CLAUDE_IMPORT})")
            if old_copy:
                print(f"Note: {claude_path} still holds an older copy of the guide from `setup-claude`. "
                      f"You can delete that copy; the current guide is in {GUIDE_FILE}.")
    except FileNotFoundError:
        print("Error: the agent guide is missing from the installed package. Reinstall maxpylang.",
              file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"Error writing to {cwd}: {exc}", file=sys.stderr)
        return 1

    print("Run this again after upgrading maxpylang to refresh the guide.")
    return 0


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        prog="maxpylang",
        description="MaxPyLang command-line tools.",
    )
    subparsers = parser.add_subparsers(dest="command")

    for name in ("setup-agent", "setup-claude"):
        sp = subparsers.add_parser(
            name,
            help=("Write the maxpylang guide for coding agents into ./AGENTS.md."
                  if name == "setup-agent" else "Same as setup-agent."),
        )
        sp.add_argument(
            "--no-claude",
            action="store_true",
            help=f"Do not create or edit {CLAUDE_FILE}.",
        )
        # kept so `setup-claude --force` from older instructions still runs; the guide is
        # always refreshed in place now, so there is nothing to force
        sp.add_argument("--force", "-f", action="store_true", help=argparse.SUPPRESS)
        sp.set_defaults(func=setup_agent)

    args = parser.parse_args(argv)

    if not hasattr(args, "func"):
        parser.print_help()
        raise SystemExit(1)

    raise SystemExit(args.func(args))


if __name__ == "__main__":
    main()
